package com.menumind.backend.entity;

import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;

/**
 * OrderItem Entity
 * 
 * Maps to 'order_items' table.
 * Crucial Snapshot Accounting:
 * Stores unitPrice and unitCost at the exact moment of order creation.
 * This guarantees that future changes to dish prices in 'menu_items'
 * never alter historical profit calculations.
 */
@Entity
@Table(name = "order_items")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class OrderItem {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "order_id", nullable = false)
    private Order order;

    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "menu_item_id", nullable = false)
    private MenuItem menuItem;

    @Column(nullable = false)
    private Integer quantity;

    @Column(name = "unit_price", nullable = false, precision = 10, scale = 2)
    private BigDecimal unitPrice;

    @Column(name = "unit_cost", nullable = false, precision = 10, scale = 2)
    private BigDecimal unitCost;

    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal subtotal;

    /**
     * Profit generated by this line item = (Unit Price - Unit Cost) * Quantity
     */
    public BigDecimal getItemProfit() {
        if (unitPrice == null || unitCost == null || quantity == null) {
            return BigDecimal.ZERO;
        }
        BigDecimal unitProfit = unitPrice.subtract(unitCost);
        return unitProfit.multiply(BigDecimal.valueOf(quantity));
    }

    /**
     * Total ingredient cost incurred = Unit Cost * Quantity
     */
    public BigDecimal getTotalCost() {
        if (unitCost == null || quantity == null) {
            return BigDecimal.ZERO;
        }
        return unitCost.multiply(BigDecimal.valueOf(quantity));
    }
}
